    private void codigotxtActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_codigotxtActionPerformed
        // TODO add your handling code here:
     String codigoBuscado = codigotxt.getText().trim();

if (codigoBuscado.isEmpty()) {
    empresatxt.setText("");
    telefonetxt.setText("");
    emailtxt.setText("");
    cnpjtxt.setText("");
    enderecotxt.setText("");
    return;
}

javax.swing.table.DefaultTableModel model =
    (javax.swing.table.DefaultTableModel) tabelafornecedor.getModel();

boolean achou = false;

for (int i = 0; i < model.getRowCount(); i++) {

    String codigoTabela = model.getValueAt(i, 0).toString();

    if (codigoTabela.equals(codigoBuscado)) {

        empresatxt.setText(model.getValueAt(i, 1).toString());
        telefonetxt.setText(model.getValueAt(i, 2).toString());
        emailtxt.setText(model.getValueAt(i, 3).toString());
        cnpjtxt.setText(model.getValueAt(i, 4).toString());
        enderecotxt.setText(model.getValueAt(i, 5).toString());

        achou = true;
        break;
    }
}

if (!achou) {
    empresatxt.setText("");
    telefonetxt.setText("");
    emailtxt.setText("");
    cnpjtxt.setText("");
    enderecotxt.setText("");
}
    }//GEN-LAST:event_codigotxtActionPerformed

