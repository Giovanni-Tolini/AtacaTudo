    private void informacaoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_informacaoActionPerformed
        // TODO add your handling code here:
        // 1. Descobre qual linha o usuário selecionou na tabela
int linhaSelecionada = tabelafornecedor.getSelectedRow();

// 2. Verifica se o usuário realmente selecionou alguma linha
if (linhaSelecionada != -1) {
    
    // Pega o código (coluna 0) e o nome (coluna 1) da linha selecionada
    String codigo = tabelafornecedor.getValueAt(linhaSelecionada, 0).toString();
    String nomeEmpresa = tabelafornecedor.getValueAt(linhaSelecionada, 1).toString();
    
    // Variáveis que vão armazenar os dados complementares
    String cnpj = "";
    String endereco = "";

    // 3. Busca os dados complementares baseados no código da empresa clicada
    switch (codigo) {
        case "001":
            cnpj = "12.345.678/0001-90";
            endereco = "Rua das Flores, 123 - Centro, São Paulo/SP";
            break;
        case "002":
            cnpj = "23.456.789/0001-12";
            endereco = "Av. dos Ipês, 456 - Vila Verde, São Paulo/SP";
            break;
        case "003":
            cnpj = "34.567.890/0001-34";
            endereco = "Rua do Trigo, 789 - Distrito Industrial, São Paulo/SP";
            break;
        case "004":
            cnpj = "45.678.901/0001-56";
            endereco = "Rodovia Anhanguera, Km 25 - Galpão 4, São Paulo/SP";
            break;
        case "005":
            cnpj = "56.789.012/0001-78";
            endereco = "Av. das Indústrias, 1500 - Parque Empresarial, São Paulo/SP";
            break;
        default:
            cnpj = "Não encontrado";
            endereco = "Não encontrado";
            break;
    }

    // 4. Exibe a mensagem personalizada apenas para a empresa selecionada
    javax.swing.JOptionPane.showMessageDialog(
            null, 
            "Empresa: " + nomeEmpresa + "\n" +
            "CNPJ: " + cnpj + "\n" +
            "Endereço: " + endereco,
            "Informações Complementares",
            javax.swing.JOptionPane.INFORMATION_MESSAGE
    );

} else {
    // Mensagem de aviso caso o usuário clique no botão sem selecionar nenhuma linha
    javax.swing.JOptionPane.showMessageDialog(
            null, 
            "Por favor, selecione uma empresa na tabela primeiro.", 
            "Aviso", 
            javax.swing.JOptionPane.WARNING_MESSAGE
    );
}
    }//GEN-LAST:event_informacaoActionPerformed

