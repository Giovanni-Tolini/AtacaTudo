    private void removerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_removerActionPerformed
        // TODO add your handling code here:
        
    javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tabelaprodutos.getModel();
    
    
    int linhaSelecionada = tabelaprodutos.getSelectedRow();
    
    
    if (linhaSelecionada == -1) {
        javax.swing.JOptionPane.showMessageDialog(null, "Por favor, selecione um produto na tabela primeiro!");
    } else {
        
        
        model.removeRow(linhaSelecionada);
        
        
        javax.swing.JOptionPane.showMessageDialog(null, "Produto removido com sucesso!");
    }
    }//GEN-LAST:event_removerActionPerformed

