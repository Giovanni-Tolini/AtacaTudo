    private void AdicionarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_AdicionarActionPerformed
        // TODO add your handling code here:
     // 1. Pega o "cérebro" da tabela para conseguir mexer nas linhas
    javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tabelaprodutos.getModel();
    
   
    int qtdAtual = Integer.parseInt(quantidade.getText());
    int qtdMinima = Integer.parseInt(estoque.getText());
    String situacao;
    
    if (qtdAtual < qtdMinima) {
        situacao = "Estoque Baixo";
    } else {
        situacao = "OK";
    }
    
    // 3. ADICIONA A LINHA NOVA NA TABELA
    model.addRow(new Object[]{
        codigo.getText(),
        produto.getText(),
        quantidade.getText(),
        estoque.getText(),
        fornecedor.getText(),
        situacao
    });
    
    
    codigo.setText("");
    produto.setText("");
    quantidade.setText("");
    estoque.setText("");
    fornecedor.setText("");
    
    
    javax.swing.JOptionPane.showMessageDialog(null, "Produto adicionado com sucesso!");
    }//GEN-LAST:event_AdicionarActionPerformed

    private void EstoquebaixoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_EstoquebaixoActionPerformed
        // TODO add your handling code here:
        
    
    javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tabelaprodutos.getModel();
    
   
    int i = 0;
    while (i < model.getRowCount()) {
        
        
        String situacao = model.getValueAt(i, 5).toString();
        
        // Se a situação for "OK", nós deletamos a linha
        if (situacao.equals("OK")) {
            model.removeRow(i); 
            // Como a linha de baixo subiu, a nova linha já está na posição 'i'.
        } else {
            // Só passamos para a próxima linha (i++) se o produto CONTINUAR na tabela
            i++;
        }
    }
    }//GEN-LAST:event_EstoquebaixoActionPerformed

