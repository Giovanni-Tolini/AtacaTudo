    private void notificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_notificarActionPerformed
        // TODO add your handling code here:

    int linhaSelecionada = tabelaalertas.getSelectedRow();
    if (linhaSelecionada == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, 
            "Por favor, selecione um fornecedor na tabela primeiro!", 
            "Aviso", 
            javax.swing.JOptionPane.WARNING_MESSAGE);
    } else {
        try {String nomeFornecedor = tabelaalertas.getValueAt(linhaSelecionada, 4).toString();
            String situacao = tabelaalertas.getValueAt(linhaSelecionada, 6).toString();
            if (situacao.equalsIgnoreCase("Estoque Baixo")) {
                javax.swing.JOptionPane.showMessageDialog(this, 
                    "Alerta de estoque enviado imediatamente para o fornecedor: " + nomeFornecedor + "!", 
                    "Notificação Enviada", 
                    javax.swing.JOptionPane.INFORMATION_MESSAGE);
            } else {javax.swing.JOptionPane.showMessageDialog(this, 
                    "O estoque para " + nomeFornecedor + " está regular.\nNão é necessário enviar notificações no momento.", 
                    "Estoque Seguro", 
                    javax.swing.JOptionPane.INFORMATION_MESSAGE);
            }
            
        } catch (Exception e) {
            // Se der qualquer erro de coluna sumida, o Java não fica mudo e te avisa aqui:
            javax.swing.JOptionPane.showMessageDialog(this, 
                "Erro ao ler os dados da tabela. Verifique a ordem das colunas!", 
                "Erro do Sistema", 
                javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }
    }//GEN-LAST:event_notificarActionPerformed

